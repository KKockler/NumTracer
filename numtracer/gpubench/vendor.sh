#!/usr/bin/env bash
# vendor.sh — copy the production flow trees into the harness, verbatim.
#
# The harness NEVER reads from or writes to the QCD codes during a measurement run; it works on
# these copies. That is what keeps the experiments from interfering with the other code, and it
# also freezes the inputs so a result stays reproducible after the QCD tree moves on.
#
# Only flows/ is vendored. gen/ (the disposable generator sources, 14 MB for Nf2) is deliberately
# NOT copied: the harness compiles the committed kernels, it does not regenerate them. Regeneration
# experiments get their own FlowDirectory under variants/.
#
# Usage:  ./vendor.sh            re-vendor both codes
#         ./vendor.sh ym         re-vendor one
set -euo pipefail

here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
qcd=${NTB_QCD_ROOT:-/mnt/data/Documents/Uni/Code/qcd-codes/vacuum}

declare -A SRC=(
  [ym]="$qcd/YangMills/SP"
  [nf2]="$qcd/QCD_Nf2/no_mesons"
)

want=("${@:-}")
[ -z "${want[0]:-}" ] && want=(ym nf2)

stamp="$here/kernels/VENDOR_STAMP"
: > "$stamp.tmp"
{
  echo "# generated by vendor.sh — do not edit"
  echo "# vendored_at_utc: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# qcd_codes_head: $(git -C "$qcd" rev-parse HEAD 2>/dev/null || echo UNKNOWN)"
  echo "# qcd_codes_dirty: $(git -C "$qcd" status --porcelain 2>/dev/null | wc -l) modified paths"
} >> "$stamp.tmp"

for tag in "${want[@]}"; do
  src="${SRC[$tag]:-}"
  [ -n "$src" ] || { echo "unknown code tag '$tag' (want: ym nf2)" >&2; exit 1; }
  [ -d "$src/flows" ] || { echo "no flows/ under $src" >&2; exit 1; }

  dst="$here/kernels/$tag"
  rm -rf "$dst"
  mkdir -p "$dst"
  cp -a "$src/flows" "$dst/flows"
  # the project config drives the quadrature orders; the harness must use the SAME ones
  for cfg in parameter.toml parameter.json; do
    [ -f "$src/$cfg" ] && cp -a "$src/$cfg" "$dst/$cfg"
  done

  n_flows=$(find "$dst/flows" -mindepth 1 -maxdepth 1 -type d | wc -l)
  n_lines=$(cat "$dst"/flows/*/kernels.hh 2>/dev/null | wc -l)
  echo "$tag: $n_flows flows, $n_lines generated lines  <- $src"
  {
    echo ""
    echo "[$tag]"
    echo "source     = $src"
    echo "flows      = $n_flows"
    echo "gen_lines  = $n_lines"
    echo "sha256:"
    (cd "$dst" && find flows -name '*.hh' -print0 | sort -z | xargs -0 sha256sum) | sed 's/^/  /'
  } >> "$stamp.tmp"
done

mv "$stamp.tmp" "$stamp"
echo "stamp -> $stamp"
