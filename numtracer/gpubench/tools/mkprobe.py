#!/usr/bin/env python3
"""mkprobe.py — build a standalone CUDA probe TU from a flow's generated kernels.hh.

The probe isolates the NumTracer-emitted part (fill + every trace body) from DiFfRG entirely, so
it compiles with a bare nvcc and no Kokkos/deal.II include closure. That is what makes a
cross-architecture SASS census possible from a machine that has none of the target GPUs: ptxas and
cuobjdump happily target sm_80/sm_90 without the hardware.

It carries __launch_bounds__(128) to match the production launch shape, and it consumes every
trace return value so nothing is dead-code-eliminated — a probe that lets the optimiser delete the
arithmetic measures nothing.

Usage:  mkprobe.py <flow_dir> -o probe.cu
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

RE_NS = re.compile(r"namespace\s+DiFfRG\s*\{\s*namespace\s+(\w+)")
RE_NENV = re.compile(r"constexpr\s+int\s+nenv\s*=\s*(\d+)")
RE_FILL = re.compile(r"void\s+fill\s*\(([^)]*)\)")
RE_TRACE = re.compile(r"\b(double|nt_complex_t)\s+(tr\d+)\s*\(")
RE_PARAM = re.compile(r"(?:\[\[maybe_unused\]\]\s*)?double\s+(\w+)")

TEMPLATE = """// GENERATED by gpubench/tools/mkprobe.py from {flow} — do not edit.
//
// Standalone SASS probe: the NumTracer emission only, no DiFfRG, no Kokkos.
#include <cmath>

// The generated header is decorated with the Kokkos macros; map them onto raw CUDA so the probe
// needs no Kokkos headers. KOKKOS_FUNCTION must stay a *declaration-capable* decorator because the
// device __noinline__ size gate emits `__attribute__((noinline))` alongside it.
#define KOKKOS_INLINE_FUNCTION       __device__ inline
#define KOKKOS_FORCEINLINE_FUNCTION  __device__ __forceinline__
#define KOKKOS_FUNCTION              __device__

#include "{header}"

namespace ns = DiFfRG::{ns};

// __launch_bounds__(128) matches the production launch shape. Without it the codegen pins
// registers differently and the census is not comparable (tests/gpu/README.md:78-81).
__global__ void __launch_bounds__(128) nt_probe(const double *__restrict__ in,
                                                double *__restrict__ out, int n)
{{
  const int i = blockIdx.x * blockDim.x + threadIdx.x;
  if (i >= n) return;

{loads}
  double f[(ns::nenv) > 0 ? (ns::nenv) : 1];
  ns::fill(f{fill_args});

  double acc = 0.;
{trace_calls}
  out[i] = acc;
}}
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("flow_dir", type=Path)
    ap.add_argument("-o", "--out", type=Path, required=True)
    args = ap.parse_args()

    hdr = args.flow_dir / "kernels.hh"
    text = hdr.read_text(errors="replace")

    m = RE_NS.search(text)
    if not m:
        print(f"{hdr}: no DiFfRG::<ns> namespace found", file=sys.stderr)
        return 1
    ns = m.group(1)

    mf = RE_FILL.search(text)
    if not mf:
        print(f"{hdr}: no fill() found", file=sys.stderr)
        return 1
    # drop the leading `double *f`
    params = [p for p in RE_PARAM.findall(mf.group(1))]

    traces = sorted(set(t for _, t in RE_TRACE.findall(text)), key=lambda s: int(s[2:]))
    if not traces:
        print(f"{hdr}: no trace functions found", file=sys.stderr)
        return 1

    # Each thread reads its own inputs so nothing is a compile-time constant.
    loads = "\n".join(f"  const double {p} = in[i * {len(params)} + {j}];"
                      for j, p in enumerate(params))
    fill_args = "".join(f", {p}" for p in params)
    calls = "\n".join(f"  acc += ns::{t}(f);" for t in traces)

    src = TEMPLATE.format(flow=args.flow_dir.name, header=hdr.resolve(), ns=ns,
                          loads=loads, fill_args=fill_args, trace_calls=calls)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(src)
    print(f"{args.flow_dir.name}: ns={ns} params={len(params)} traces={len(traces)} -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
